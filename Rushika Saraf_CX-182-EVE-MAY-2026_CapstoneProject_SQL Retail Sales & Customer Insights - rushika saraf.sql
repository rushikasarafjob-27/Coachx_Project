--1. find total revenue by city.

select customers.city, sum(orders.amount) as totalrevenue
from customers
inner join orders on customers.customerid = orders.customerid
group by customers.city
order by totalrevenue desc;

--2. identify top 3 customers by total spending.

select top 3 customers.customername, sum(orders.amount) as totalspent
from customers
inner join orders on customers.customerid = orders.customerid
group by customers.customername
order by totalspent desc;


--3. find customers who placed more than 2 orders.

select customers.customername, count(orders.orderid) as ordercount
from customers
inner join orders on customers.customerid = orders.customerid
group by customers.customername
having count(orders.orderid) > 2
order by ordercount desc;

