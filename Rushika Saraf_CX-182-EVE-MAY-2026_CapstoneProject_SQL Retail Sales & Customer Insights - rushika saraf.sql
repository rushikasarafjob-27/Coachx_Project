--5. find monthly revenue trend.

select 
    year(orders.orderdate) as orderyear,
    month(orders.orderdate) as ordermonth,
    sum(orders.amount) as monthlyrevenue
from orders
group by year(orders.orderdate), month(orders.orderdate)
order by orderyear, ordermonth;

-- 6. find customers who ordered in more than one month.

select customers.customername, count(distinct month(orders.orderdate)) as monthsordered
from customers
inner join orders on customers.customerid = orders.customerid
group by customers.customername
having count(distinct month(orders.orderdate)) > 1
order by monthsordered desc;

--7. find customers whose total spend is above average.
SELECT
    Customers.CustomerID,
    Customers.CustomerName,
    SUM(Orders.Amount) AS TotalSpend
FROM Customers
INNER JOIN Orders
    ON Customers.CustomerID = Orders.CustomerID
GROUP BY
    Customers.CustomerID,
    Customers.CustomerName
HAVING SUM(Orders.Amount) >
(
    SELECT AVG(CustomerTotalSpend)
    FROM
    (
        SELECT
            Orders.CustomerID,
            SUM(Orders.Amount) AS CustomerTotalSpend
        FROM Orders
        GROUP BY Orders.CustomerID
    ) AS CustomerSpendingSummary
);
--8. find revenue generated by each category.

select products.category, sum(orders.amount) as totalrevenue
from orders
inner join orderdetails on orders.orderid = orderdetails.orderid
inner join products on orderdetails.productid = products.productid
group by products.category
order by totalrevenue desc;

--9. find first and last order date for each customer.

select customers.customername,
       min(orders.orderdate) as firstorderdate,
       max(orders.orderdate) as lastorderdate
from customers
inner join orders on customers.customerid = orders.customerid
group by customers.customername
order by customers.customername;

--10. find customers who bought electronics and spent more than 10,000.

SELECT
    Customers.CustomerID,
    Customers.CustomerName,
    SUM(Orders.Amount) AS TotalSpend
FROM Customers
INNER JOIN Orders
    ON Customers.CustomerID = Orders.CustomerID
WHERE Customers.CustomerID IN
(
    SELECT DISTINCT Orders.CustomerID
    FROM Orders
    INNER JOIN OrderDetails
        ON Orders.OrderID = OrderDetails.OrderID
    INNER JOIN Products
        ON OrderDetails.ProductID = Products.ProductID
    WHERE Products.Category = 'Electronics'
)
GROUP BY
    Customers.CustomerID,
    Customers.CustomerName
HAVING SUM(Orders.Amount) > 10000;
